#!/usr/bin/env python3
"""Builds main/LandMask.h: which 5-degree cells contain land, for Diyanet's Hijri month rule (the
crescent conditions must hold over land somewhere). Source: Natural Earth 1:110m land polygons
(public domain), https://www.naturalearthdata.com/.

    curl -O https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
    python tools/make_land_mask.py ne_110m_land.geojson main/LandMask.h

A cell counts as land when any of nine points spread over it lies inside a land polygon, so that
coasts are kept. Latitudes from 60 S to 75 N: farther south lies only Antarctica.
"""

import json
import sys

CELL = 5
SOUTH = -60
NORTH = 75
ROWS = (NORTH - SOUTH) // CELL
COLUMNS = 360 // CELL


def inside(ring, x, y):
    """Ray casting: is the point inside the polygon ring (a list of [lon, lat])?"""
    result = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            result = not result
        j = i
    return result


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    with open(sys.argv[1], encoding='utf-8') as source:
        data = json.load(source)
    rings = []
    for feature in data['features']:
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        for polygon in polygons:
            rings.append(polygon[0])  # outer ring; lakes are ignored

    bits = []
    for row in range(ROWS):
        south = SOUTH + row * CELL
        for column in range(COLUMNS):
            west = -180 + column * CELL
            land = False
            for dy in (0.5, 2.5, 4.5):
                for dx in (0.5, 2.5, 4.5):
                    if any(inside(ring, west + dx, south + dy) for ring in rings):
                        land = True
            bits.append(land)

    data = bytearray((len(bits) + 7) // 8)
    for i, land in enumerate(bits):
        if land:
            data[i // 8] |= 1 << (i % 8)
    with open(sys.argv[2], 'w', encoding='utf-8') as output:
        output.write('#pragma once\n\n')
        output.write('// Generated by tools/make_land_mask.py from Natural Earth 1:110m land (public domain).\n')
        output.write(f'// Bit (row * {COLUMNS} + column): the {CELL}-degree cell with its south-west corner at\n')
        output.write(f'// latitude {SOUTH} + row * {CELL}, longitude -180 + column * {CELL} contains land.\n\n')
        output.write('#include <cstdint>\n\n')
        output.write(f'static const int s_landCellDegrees = {CELL};\n')
        output.write(f'static const int s_landSouth = {SOUTH};\n')
        output.write(f'static const int s_landRows = {ROWS};\n')
        output.write(f'static const int s_landColumns = {COLUMNS};\n')
        output.write(f'static const uint8_t s_landMask[{len(data)}] = {{\n')
        for i in range(0, len(data), 16):
            output.write('    ' + ', '.join(f'0x{byte:02X}' for byte in data[i:i + 16]) + ',\n')
        output.write('};\n')
    print(f'{sum(bits)} of {len(bits)} cells contain land')
    return 0


if __name__ == '__main__':
    sys.exit(main())
