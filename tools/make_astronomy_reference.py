#!/usr/bin/env python3
"""Reference values for tests/AstronomyTest.cpp, computed with Skyfield and the JPL DE421
ephemeris, which are far more accurate than the watch's series.

    sh tools/setup_reference.sh                      # once
    tools/.venv/bin/python tools/make_astronomy_reference.py > tests/astronomy_reference.csv

Each row: case, latitude, longitude, local midnight (Unix s), quantity, value. Times are Unix
seconds or "none"; angles are degrees. The test compares each quantity within its tolerance.
"""

import datetime
import math
import os

from skyfield import almanac
from skyfield.api import Loader, wgs84

HERE = os.path.dirname(os.path.abspath(__file__))
load = Loader(os.path.join(HERE, '.venv', 'skyfield-data'))
eph = load('de421.bsp')
ts = load.timescale()
sun, moon, earth = eph['sun'], eph['moon'], eph['earth']

# Name, latitude, longitude, UTC offset (hours) that defines the local day.
PLACES = [
    ('ankara', 39.93, 32.86, 3),
    ('istanbul', 41.01, 28.98, 3),
    ('tromso', 69.65, 18.96, 1),
    ('reykjavik', 64.15, -21.94, 0),
    ('sydney', -33.87, 151.21, 10),
    ('quito', -0.18, -78.47, -5),
    ('honolulu', 21.31, -157.86, -10),
]
# Solstices, equinoxes and days after new Moons (for the crescent).
DATES = ['2026-03-20', '2026-03-21', '2026-06-21', '2026-09-23', '2026-11-10', '2026-11-11', '2026-11-12',
         '2026-12-21', '2027-01-15']

# Geometric altitudes of the Sun's centre: twilight, golden and blue hour limits.
THRESHOLDS = [('civil', -6.0), ('nautical', -12.0), ('astronomical', -18.0), ('golden', 6.0), ('blue', -4.0)]


def unix(t):
    return round(t.utc_datetime().timestamp())


def first(times, flags=None):
    for i, t in enumerate(times):
        if flags is None or flags[i]:
            return str(unix(t))
    return 'none'


def crossings(place, start, end, threshold):
    observer = earth + place

    def above(t):
        return observer.at(t).observe(sun).apparent().altaz()[0].degrees > threshold
    above.step_days = 1 / 48
    times, values = almanac.find_discrete(start, end, above)
    rising = [t for t, v in zip(times, values) if v]
    setting = [t for t, v in zip(times, values) if not v]
    return first(rising), first(setting)


def crescentV(place, start, end):
    """Odeh's V for the evening (topocentric, airless, at the best time), or 'none'."""
    observer = earth + place
    sunsets, flags = almanac.find_settings(observer, sun, start, end)
    if not len(sunsets) or not flags[0]:
        return 'none'
    sunset = sunsets[0]
    moonsets, flags = almanac.find_settings(observer, moon, sunset, sunset + 0.5)
    if not len(moonsets) or not flags[0]:
        return 'none'
    phaseTimes, phases = almanac.find_discrete(sunset - 3, sunset, almanac.moon_phases(eph))
    newMoons = [t for t, p in zip(phaseTimes, phases) if p == 0]
    best = ts.tt_jd(sunset.tt + (moonsets[0].tt - sunset.tt) * 4 / 9)
    if not newMoons or best.tt < newMoons[-1].tt:
        return 'none'
    moonApparent = observer.at(best).observe(moon).apparent()
    sunApparent = observer.at(best).observe(sun).apparent()
    arcv = moonApparent.altaz()[0].degrees - sunApparent.altaz()[0].degrees
    arcl = moonApparent.separation_from(sunApparent).radians
    semiDiameter = math.degrees(math.asin(1737.4 / moonApparent.distance().km)) * 60
    width = semiDiameter * (1 - math.cos(arcl))
    return f'{arcv - (7.1651 - 6.3226 * width + 0.7319 * width ** 2 - 0.1018 * width ** 3):.4f}'


def altaz(place, body, t):
    altitude, azimuth, _ = (earth + place).at(t).observe(body).apparent().altaz()
    return altitude.degrees, azimuth.degrees


def main():
    print('# Generated by tools/make_astronomy_reference.py (Skyfield, JPL DE421).')
    print('case,latitude,longitude,midnight,quantity,value')
    for name, latitude, longitude, offset in PLACES:
        place = wgs84.latlon(latitude, longitude)
        observer = earth + place
        for date in DATES:
            year, month, day = (int(part) for part in date.split('-'))
            midnight = datetime.datetime(year, month, day, tzinfo=datetime.timezone.utc) - datetime.timedelta(hours=offset)
            start = ts.from_datetime(midnight)
            end = ts.from_datetime(midnight + datetime.timedelta(days=1))
            rows = []
            times, flags = almanac.find_risings(observer, sun, start, end)
            rows.append(('sun_rise', first(times, flags)))
            times, flags = almanac.find_settings(observer, sun, start, end)
            rows.append(('sun_set', first(times, flags)))
            for label, threshold in THRESHOLDS:
                rising, setting = crossings(place, start, end, threshold)
                rows.append((f'{label}_rise', rising))
                rows.append((f'{label}_set', setting))
            transits = almanac.find_transits(observer, sun, start, end)
            rows.append(('noon', first(transits)))
            if len(transits):
                rows.append(('noon_altitude', f'{altaz(place, sun, transits[0])[0]:.4f}'))
            times, flags = almanac.find_risings(observer, moon, start, end)
            rows.append(('moon_rise', first(times, flags)))
            times, flags = almanac.find_settings(observer, moon, start, end)
            rows.append(('moon_set', first(times, flags)))
            for hour in (9, 21):
                t = ts.from_datetime(midnight + datetime.timedelta(hours=hour))
                altitude, azimuth = altaz(place, sun, t)
                rows.append((f'sun_altitude_{hour}', f'{altitude:.4f}'))
                rows.append((f'sun_azimuth_{hour}', f'{azimuth:.4f}'))
                altitude, azimuth = altaz(place, moon, t)
                rows.append((f'moon_altitude_{hour}', f'{altitude:.4f}'))
                rows.append((f'moon_azimuth_{hour}', f'{azimuth:.4f}'))
            noonLocal = ts.from_datetime(midnight + datetime.timedelta(hours=12))
            rows.append(('moon_illumination_12', f'{almanac.fraction_illuminated(eph, "moon", noonLocal):.5f}'))
            rows.append(('moon_elongation_12', f'{almanac.moon_phase(eph, noonLocal).degrees:.4f}'))
            phaseTimes, phases = almanac.find_discrete(noonLocal - 32, noonLocal, almanac.moon_phases(eph))
            newMoons = [t for t, p in zip(phaseTimes, phases) if p == 0]
            rows.append(('moon_age_12', f'{(noonLocal - newMoons[-1]):.5f}'))
            seasonTimes, seasons = almanac.find_discrete(start, start + 120, almanac.seasons(eph))
            rows.append(('next_season', str(unix(seasonTimes[0]))))
            rows.append(('next_season_index', str(int(seasons[0]))))
            rows.append(('crescent_v', crescentV(place, start, end)))
            for quantity, value in rows:
                print(f'{name}-{date},{latitude},{longitude},{int(midnight.timestamp())},{quantity},{value}')


if __name__ == '__main__':
    main()
