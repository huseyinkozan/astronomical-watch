#!/usr/bin/env python3
"""Builds the setup portal's city list (main/portal/cities.js) from GeoNames.

Selection: the Turkish province seats (feature PPLA in TR), every capital (PPLC) and every
city with at least one million inhabitants. GeoNames data is CC BY 4.0; the portal page
names the source.

    curl -O https://download.geonames.org/export/dump/cities15000.zip
    unzip cities15000.zip
    python tools/make_cities.py cities15000.txt main/portal/cities.js
"""

import sys

NAME = 1
LATITUDE = 4
LONGITUDE = 5
FEATURE_CODE = 7
COUNTRY = 8
POPULATION = 14


def selected(row):
    if row[COUNTRY] == 'TR' and row[FEATURE_CODE] == 'PPLA':
        return True
    if row[FEATURE_CODE] == 'PPLC':
        return True
    return int(row[POPULATION] or 0) >= 1000000


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    rows = []
    with open(sys.argv[1], encoding='utf-8') as source:
        for line in source:
            row = line.rstrip('\n').split('\t')
            if selected(row):
                # '|' separates the fields in the output.
                name = row[NAME].replace('|', ' ')
                rows.append((row[COUNTRY], name, float(row[LATITUDE]), float(row[LONGITUDE])))
    rows.sort()
    with open(sys.argv[2], 'w', encoding='utf-8') as output:
        output.write('// Generated by tools/make_cities.py from GeoNames cities15000 (CC BY 4.0).\n')
        output.write('// Country code|name|latitude|longitude\n')
        output.write('const CITIES = `\n')
        for country, name, latitude, longitude in rows:
            output.write(f'{country}|{name}|{latitude:.4f}|{longitude:.4f}\n')
        output.write('`;\n')
    print(f'{len(rows)} cities')
    return 0


if __name__ == '__main__':
    sys.exit(main())
