struct Art
{
    const char *const *rows;
    int height;
};

static const Art s_art[AlarmIcons::IconCount] = {
    { s_smallBell, sizeof( s_smallBell ) / sizeof( s_smallBell[0] ) },
    { s_bell, sizeof( s_bell ) / sizeof( s_bell[0] ) },
    { s_hourglass, sizeof( s_hourglass ) / sizeof( s_hourglass[0] ) },
};

int AlarmIcons::width( Icon icon )
{
    return static_cast<int>( strlen( s_art[icon].rows[0] ) );
}

int AlarmIcons::height( Icon icon )
{
    return s_art[icon].height;
}

AlarmIcons::Pixel AlarmIcons::pixel( Icon icon, int x, int y )
{
    if ( x < 0 || y < 0 || x >= width( icon ) || y >= height( icon ) ) {
        return Empty;
    }
    const char c = s_art[icon].rows[y][x];
    return c == '#' ? Lit : ( c == 'o' ? Sand : Empty );
}
